const MIN_WORD_LEN: usize = 4;
const MAX_WORD_LEN: usize = 9;

/// True when `word` is a known English word that collides with Vietnamese Telex.
pub fn is_english(word: &str) -> bool {
    if !(MIN_WORD_LEN..=MAX_WORD_LEN).contains(&word.len()) {
        return false;
    }
    if VIETNAMESE_OVERRIDES.contains(&word) {
        return false;
    }
    WORDS.binary_search(&word).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_common_collisions() {
        for word in ["test", "text", "best", "cost", "choose", "church", "boring"] {
            assert!(is_english(word), "{word}");
        }
        for word in ["vieejt", "tieengs", "hoas", "suawr", "nuawx", "suwra"] {
            assert!(!is_english(word), "{word}");
        }
        // Obscure dictionary words that collide with common Vietnamese spellings.
        assert!(!is_english("theer"), "theer must render as thể");
    }

    #[test]
    fn words_are_sorted_and_within_length_bounds() {
        assert!(WORDS.windows(2).all(|w| w[0] < w[1]));
        for &word in WORDS {
            assert!(
                (MIN_WORD_LEN..=MAX_WORD_LEN).contains(&word.len()),
                "word out of length bounds: {word}"
            );
            if VIETNAMESE_OVERRIDES.contains(&word) {
                assert!(!is_english(word), "override should be false: {word}");
            } else {
                assert!(is_english(word), "word should match: {word}");
            }
        }
        for &override_word in VIETNAMESE_OVERRIDES {
            assert!(!is_english(override_word), "override: {override_word}");
        }
    }
}
